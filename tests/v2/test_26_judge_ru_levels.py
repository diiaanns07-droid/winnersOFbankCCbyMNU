"""№26, релиз: латинские уровни (critical/major/minor) в текстах судьи → правильный русский.

Формы взяты из живых ответов судьи sonnet и haiku (чек-лист, обоснование, причины): «только замечание minor»
превращалось в «только замечание незначительные дефекты», «понижен до minor» — в «до незначительные дефекты».
"""
from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from bcc_review.v2.stages import judge  # noqa: E402

CASES = [
    ("только замечание minor.", "только незначительное замечание."),
    ("одно замечание minor на документ.", "одно незначительное замечание на документ."),
    ("Отсутствие ID и приоритетов — minor, одно замечание", "Отсутствие ID и приоритетов — незначительное замечание, одно замечание"),
    ("понижен до minor.", "понижен до незначительного."),
    ("нет основания для major: ключ", "нет основания для существенного: ключ"),
    ("уровень major, не critical.", "уровень «существенный», не критичный."),
    ("с уровнем critical", "с уровнем «критичный»"),
    ("дефект major по строкам", "существенный дефект по строкам"),
    ("Critical-дефектов нет, поэтому", "Критичных дефектов нет, поэтому"),
    ("есть четыре critical, блокирующие", "есть четыре критичных дефекта, блокирующие"),
    ("нет critical, 2 major.", "нет критичных дефектов, 2 существенных дефекта."),
    ("critical-дефект D-01", "критичный дефект D-01"),
    ("есть только minor-замечания", "есть только незначительные замечания"),
    ("major-замечание", "существенное замечание"),
    ("оценён как major", "оценён как существенный"),
    ("только minor.", "только незначительные дефекты."),
]


@pytest.mark.parametrize("src,want", CASES)
def test_levels_to_russian(src, want):
    assert judge._ru_levels(src) == want


def test_no_latin_level_left():
    for src, _ in CASES:
        out = judge._ru_levels(src)
        assert not any(w in out.lower() for w in ("critical", "major", "minor")), out
