def sections(lines: list[str]) -> list[str]:
    """Путь заголовков для каждой строки (без заголовка документа уровня 1)."""
    path: list[tuple[int, str]] = []
    out = []
    for raw in lines:
        m = re.match(r"^(#{2,6})\s+(.*)$", raw)
        if m:
            level = len(m.group(1))
            path = [p for p in path if p[0] < level] + [(level, m.group(2).strip())]
        out.append(" › ".join(t for _, t in path))
    return out


