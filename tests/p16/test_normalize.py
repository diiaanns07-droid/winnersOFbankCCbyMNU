@pytest.mark.parametrize("name,gold,pred,expected", CASES, ids=[c[0] for c in CASES])
def test_anchor_rule(name, gold, pred, expected):
    assert coverage(gold, pred).covered is expected


def test_pdf_interleaved_cells_go_to_review_not_match():
    """Перемешанные ячейки PDF не засчитываются автоматически, но видны как частичное покрытие."""
    c = coverage(G4, "Порог 1 000 ₸, сумма Оператор сообщает Одно пополнение на\n2 000 ₸ баланс 900 ₸ 2 000 ₸")
    assert not c.covered and c.partial


def test_tokens_normalize_numbers_and_quotes():
    assert tokens("от 1 000 до «3 000 000» ₸") == ["от", "1000", "до", "3000000", "₸"]
    assert tokens("Ёлка") == ["елка"]
