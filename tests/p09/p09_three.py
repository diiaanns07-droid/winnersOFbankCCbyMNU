EDITIONS = {"v1": V1, "v2": V2, "v3": V3}
CREDIT_V3 = "Держатель кредитной карты получает push не позднее 60 секунд"


def v3_unreadable_bytes() -> bytes:
    """Неполный повторный прогон: два байта кредитного пункта не декодируются (reader → decode_error)."""
    return V3.encode("utf-8").replace("Держатель кредитной".encode(), b"\xff\xfe " + "Держатель кредитной".encode())


def write_inputs(folder: Path) -> dict[str, Path]:
    folder.mkdir(parents=True, exist_ok=True)
    out = {}
    for name, text in EDITIONS.items():
        p = folder / f"{name}.md"
        p.write_bytes(text.encode("utf-8"))
        out[name] = p
    bad = folder / "v3_unreadable.md"
    bad.write_bytes(v3_unreadable_bytes())
    out["v3_unreadable"] = bad
    return out


def run_standard(src: Path, out_md: Path, *, compare: Path | None = None, **extra) -> dict:
    """Штатный путь: движок Max (`run_review`), офлайн-правила без модели, кэш выключен."""
    from bcc_review import run_review

    opts = {
        "offline_lint": True,
        "use_cache": False,
        "trace": False,
        "artifacts_dir": str(out_md.with_suffix(".artifacts")),
    }
    if compare is not None:
        opts["compare_path"] = str(compare)
    opts.update(extra)
    run_review(src, out_md, options=opts)
    return json.loads(out_md.with_suffix(".json").read_text(encoding="utf-8"))
