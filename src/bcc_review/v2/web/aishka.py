# настроения знакомства (tty_agent, №40) → кадры AIshka
MOODS = {"idle": "idle", "blink": "blink", "look": "wink", "wink": "wink", "verified": "tenge", "tenge": "tenge",
         "happy": "happy", "alert": "oops", "oops": "oops", "ready": "ready", "speak": "speak", "work": "work0",
         "analyzing": "work0"}
ASCII = ("     /\\", "    /  \\", "   / {face} \\", "  /  {mouth}  \\", " /________\\")
ASCII_FACES = {"idle": ("oo", "--"), "blink": ("--", "--"), "wink": ("-o", "--"), "happy": ("^^", "\\/"),
               "tenge": ("TT", "\\/"), "ready": ("oo", "--"), "oops": ("OO", "()"), "speak": ("oo", "()"),
               "work": ("==", "--")}
_LEVELS = (0, 95, 135, 175, 215, 255)


def frame_name(name: str) -> str:
    """Имя кадра AIshka для настроения знакомства: analyzing3 → work3, look → wink, alert → oops."""
    m = re.fullmatch(r"(analyzing|work)(\d+)", name)
    if m:
        return f"work{int(m.group(2)) % 6}"
    return MOODS.get(name, name if name in FRAMES else "idle")


def _rgb(hexcolor: str) -> tuple[int, int, int]:
    h = hexcolor.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def xterm256(rgb: tuple[int, int, int]) -> int:
    """Ближайший цвет палитры xterm: куб 6×6×6 или шкала серого."""
    def near(v: int) -> int:
        return min(range(6), key=lambda i: abs(_LEVELS[i] - v))
    r, g, b = (near(v) for v in rgb)
    cube = 16 + 36 * r + 6 * g + b
    cube_rgb = (_LEVELS[r], _LEVELS[g], _LEVELS[b])
    gray_i = max(0, min(23, round((sum(rgb) / 3 - 8) / 10)))
    gray = 8 + gray_i * 10
    dist = lambda a: sum((x - y) ** 2 for x, y in zip(a, rgb))  # noqa: E731
    return cube if dist(cube_rgb) <= dist((gray, gray, gray)) else 232 + gray_i


def _sgr(idx: int, mode: str, bg: bool) -> str:
    rgb = _rgb(PALETTE[idx - 1])
    if mode == "truecolor":
        return f"{48 if bg else 38};2;{rgb[0]};{rgb[1]};{rgb[2]}"
    return f"{48 if bg else 38};5;{xterm256(rgb)}"


def ascii_bot(name: str) -> list[str]:
    key = frame_name(name)
    face, mouth = ASCII_FACES.get(re.sub(r"\d+$", "", key), ASCII_FACES["idle"])
    return [ln.format(face=face, mouth=mouth) for ln in ASCII]


def render(name: str, mode: str, *, small: bool = False, indent: int = 2) -> list[str]:
    """Строки терминала с AIshka: полублок «▀» — верхний пиксель цветом текста, нижний — фоном.

    ``mode`` — 'truecolor', '256' или 'ascii' (как ``tty_agent.color_mode``). ``small`` принят для совместимости:
    AIshka и так 35×19 — помещается в окно 80×24.
    """
    if mode == "ascii":
        return [" " * indent + ln for ln in ascii_bot(name)]
    rows = [[".ABCDEFGHIJKLMNOP".index(ch) for ch in row] for row in FRAMES[frame_name(name)]]
    lines = []
    pad = " " * indent
    for y in range(0, len(rows), 2):
        top, bot = rows[y], rows[y + 1]
        out, cur = [pad], ""
        for t, b in zip(top, bot):
            if not t and not b:
                cell, sgr = " ", "0"
            elif t and b:
                cell, sgr = "▀", _sgr(t, mode, False) + ";" + _sgr(b, mode, True)
            elif t:
                cell, sgr = "▀", "0;" + _sgr(t, mode, False)
            else:
                cell, sgr = "▄", "0;" + _sgr(b, mode, False)
            if sgr != cur:
                out.append(f"\x1b[{sgr}m")
                cur = sgr
            out.append(cell)
        out.append("\x1b[0m")
        lines.append("".join(out))
    return lines


