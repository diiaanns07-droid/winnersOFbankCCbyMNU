def replace(find: str, new: str) -> dict:
    return {"op": "replace", "find": find, "new": new}


def insert_after(after: str, text: str, block: bool = False) -> dict:
    """Вставить строку text после строки, содержащей after. block=True — отдельным абзацем."""
    return {"op": "insert_after", "after": after, "text": text, "block": block}


def delete_section(start: str, until: str) -> dict:
    """Удалить строки от строки, начинающейся с start, до строки, начинающейся с until (не включая)."""
    return {"op": "delete_section", "start": start, "until": until}


def delete_line(find: str) -> dict:
    return {"op": "delete_line", "find": find}


def conflict(a: str, b: str, scenario: str) -> dict:
    return {"anchors": [{"role": "a", "quote": a}, {"role": "b", "quote": b}], "anchor_policy": "all",
            "scenario": scenario}


def promise(*quotes: str) -> dict:
    return {"anchors": [{"role": "promise", "quote": q} for q in quotes], "anchor_policy": "any"}


def control(quote: str) -> dict:
    return {"anchors": [{"role": "control", "quote": quote}]}


